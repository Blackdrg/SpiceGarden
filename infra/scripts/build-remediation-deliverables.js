const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '../..');
const REMEDIATION_DIR = path.join(ROOT_DIR, 'reports/performance/remediation');

if (!fs.existsSync(REMEDIATION_DIR)) {
  fs.mkdirSync(REMEDIATION_DIR, { recursive: true });
}

console.log('Writing remediation deliverables to:', REMEDIATION_DIR);

function writeDoc(relPath, content) {
  const fullPath = path.join(ROOT_DIR, relPath);
  const dir = path.dirname(fullPath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(fullPath, content.trim() + '\n', 'utf8');
  console.log('Created:', relPath);
}

