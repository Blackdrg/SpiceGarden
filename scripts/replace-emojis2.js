  const matches = c.match(regex);
  if (!matches || matches.length === 0) {
    console.log(fp + ': CLEAN');
    return;
  }
  const unique = [...new Set(matches)];
  console.log(fp + ': ' + matches.length + ' emojis (' + unique.length + ' unique)');
